//go:build darwin

package platform

import (
	"errors"
	"log"
	"runtime"
	"sync"
	"time"

	"github.com/IcyBlue17/hoshiro/internal/macos"
)

const (
	restoreDelay   = 450 * time.Millisecond
	typeString     = "public.utf8-plain-text"
	typeTransient  = "org.nspasteboard.TransientType"
	typeAutoGen    = "org.nspasteboard.AutoGeneratedType"
	maxFlavorBytes = 64 << 20
)

type flavor struct {
	typ  string
	data []byte
}

// snapshot is everything that was on the pasteboard: items -> flavors.
type snapshot [][]flavor

type pendingRestore struct {
	snap       snapshot
	generation uint64
	change     int
}

var (
	pasteMu    sync.Mutex
	pending    *pendingRestore
	generation uint64
)

func pasteboard() macos.ID { return macos.Send(macos.Class("NSPasteboard"), "generalPasteboard") }

func snapshotPasteboard(pb macos.ID) snapshot {
	var snap snapshot
	items := macos.Send(pb, "pasteboardItems")
	if items == 0 {
		return snap
	}
	for i := range macos.SendInt(items, "count") {
		item := macos.Send(items, "objectAtIndex:", uint(i))
		types := macos.Send(item, "types")
		var fl []flavor
		for j := range macos.SendInt(types, "count") {
			t := macos.Send(types, "objectAtIndex:", uint(j))
			d := macos.Send(item, "dataForType:", t)
			if d == 0 {
				continue
			}
			if macos.SendInt(d, "length") > maxFlavorBytes {
				continue
			}
			fl = append(fl, flavor{macos.GoNS(t), macos.DataBytes(uintptr(d))})
		}
		if len(fl) > 0 {
			snap = append(snap, fl)
		}
	}
	return snap
}

func restoreSnapshot(pb macos.ID, snap snapshot) {
	macos.Send(pb, "clearContents")
	if len(snap) == 0 {
		return
	}
	arr := macos.Send(macos.Class("NSMutableArray"), "array")
	for _, fl := range snap {
		item := macos.Send(macos.Send(macos.Class("NSPasteboardItem"), "alloc"), "init")
		for _, f := range fl {
			macos.Send(item, "setData:forType:", macos.NSData(f.data), macos.NSString(f.typ))
		}
		macos.Send(arr, "addObject:", item)
		macos.Send(item, "release")
	}
	if !macos.SendBool(pb, "writeObjects:", arr) {
		log.Print("restoring the pasteboard failed")
	}
}

func writeTransientText(pb macos.ID, text string) bool {
	macos.Send(pb, "clearContents")
	item := macos.Send(macos.Send(macos.Class("NSPasteboardItem"), "alloc"), "init")
	defer macos.Send(item, "release")
	ok := macos.SendBool(item, "setString:forType:", macos.NSString(text), macos.NSString(typeString))
	empty := macos.NSData(nil)
	macos.Send(item, "setData:forType:", empty, macos.NSString(typeTransient))
	macos.Send(item, "setData:forType:", empty, macos.NSString(typeAutoGen))
	arr := macos.Send(macos.Class("NSArray"), "arrayWithObject:", item)
	return ok && macos.SendBool(pb, "writeObjects:", arr)
}

// InsertText pastes text at the caret of the frontmost app: snapshot the
// pasteboard, write the text (flagged transient so clipboard managers ignore
// it), post Cmd+V, and restore the original pasteboard ~450 ms later unless
// the user copied something in the meantime.
func InsertText(text string) error {
	if text == "" {
		return nil
	}
	runtime.LockOSThread()
	defer runtime.UnlockOSThread()
	var gen uint64
	var err error
	macos.Pool(func() {
		pb := pasteboard()
		pasteMu.Lock()
		defer pasteMu.Unlock()
		// A previous paste may still be waiting to restore: its snapshot is the real clipboard.
		var snap snapshot
		if pending != nil {
			snap = pending.snap
			pending = nil
		} else {
			snap = snapshotPasteboard(pb)
		}
		if !writeTransientText(pb, text) {
			restoreSnapshot(pb, snap)
			err = errors.New("could not write the text to the pasteboard")
			return
		}
		generation++
		gen = generation
		pending = &pendingRestore{snap, gen, macos.SendInt(pb, "changeCount")}
	})
	if err != nil {
		return err
	}
	if err := postKeyPress(keycodeForChar('v'), flagCommand); err != nil {
		finishRestore(gen, true)
		return err
	}
	go func() {
		time.Sleep(restoreDelay)
		finishRestore(gen, false)
	}()
	return nil
}

// ReplaceSelection replaces the selection with text (paste replaces the selection).
func ReplaceSelection(text string) error { return InsertText(text) }

func finishRestore(gen uint64, force bool) {
	runtime.LockOSThread()
	defer runtime.UnlockOSThread()
	pasteMu.Lock()
	defer pasteMu.Unlock()
	if pending == nil || pending.generation != gen {
		return // superseded by a newer paste or an explicit copy
	}
	p := pending
	pending = nil
	macos.Pool(func() {
		pb := pasteboard()
		if force || macos.SendInt(pb, "changeCount") == p.change {
			restoreSnapshot(pb, p.snap)
		}
	})
}

// CopyToClipboard puts text on the clipboard permanently (user-initiated copy).
func CopyToClipboard(text string) error {
	runtime.LockOSThread()
	defer runtime.UnlockOSThread()
	pasteMu.Lock()
	pending = nil // a delayed restore must never overwrite an explicit copy
	pasteMu.Unlock()
	ok := false
	macos.Pool(func() {
		pb := pasteboard()
		macos.Send(pb, "clearContents")
		ok = macos.SendBool(pb, "setString:forType:", macos.NSString(text), macos.NSString(typeString))
	})
	if !ok {
		return errors.New("could not write to the pasteboard")
	}
	return nil
}

// ── keycode of a letter in the current ASCII-capable layout (Dvorak etc.) ──

type cachedCode struct {
	at   time.Time
	code uint16
}

var (
	codeMu    sync.Mutex
	codeCache = map[rune]cachedCode{}
)

func defaultKeycode(ch rune) uint16 {
	if ch == 'c' {
		return 8
	}
	return 9
}

func keycodeForChar(ch rune) uint16 {
	codeMu.Lock()
	if c, ok := codeCache[ch]; ok && time.Since(c.at) < 10*time.Second {
		codeMu.Unlock()
		return c.code
	}
	codeMu.Unlock()
	// TIS must run on the main thread on recent macOS; never wait long for it.
	type res struct {
		code uint16
		ok   bool
	}
	r, done := onMainTimeout(40*time.Millisecond, func() res { c, ok := lookupKeycode(ch); return res{c, ok} })
	codeMu.Lock()
	defer codeMu.Unlock()
	if done && r.ok {
		codeCache[ch] = cachedCode{time.Now(), r.code}
		return r.code
	}
	if c, ok := codeCache[ch]; ok {
		return c.code
	}
	return defaultKeycode(ch)
}

func lookupKeycode(ch rune) (uint16, bool) {
	src := tisCopyASCIILayout()
	if src == 0 {
		return 0, false
	}
	defer macos.CFRelease(src)
	data := tisGetProperty(src, kTISUnicodeLayout)
	if data == 0 {
		return 0, false
	}
	layout := macos.CFDataGetBytePtr(data)
	kbd := uint32(lmGetKbdType())
	translate := func(code uint16) rune {
		var dead uint32
		var n int
		var buf [4]uint16
		if ucKeyTranslate(layout, code, 0, 0, kbd, 1, &dead, len(buf), &n, &buf[0]) != 0 || n == 0 {
			return 0
		}
		return rune(buf[0])
	}
	if p := defaultKeycode(ch); translate(p) == ch {
		return p, true
	}
	for c := uint16(0); c < 128; c++ {
		if translate(c) == ch {
			return c, true
		}
	}
	return 0, false
}
